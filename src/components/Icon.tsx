/** Chooses a department icon. Only a visual choice: it does not add any information. */
export function departmentIcon(slug: string): IconName {
  if (slug === "cardiologist") return "heart-pulse";
  if (slug.startsWith("diabetologist")) return "droplet";
  if (slug === "sonologist") return "scan";
  return "stethoscope";
}
