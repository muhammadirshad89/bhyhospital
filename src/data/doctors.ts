const published = { verified: true, active: true, approved: true, deleted: false };

const day = (d: Weekday, start: string, end: string): OpdDay => ({ day: d, sessions: [{ start, end }] });
/** One schedule line as structured data. label = e.g. "Emergency Department"; note = e.g. "Pre-Appointment". */
const S = (days: Weekday[], start: string, end: string, label?: string, note?: string): OpdDay[] =>
  days.map((d) => ({ day: d, sessions: [label ? { start, end, label } : { start, end }], ...(note ? { note } : {}) }));
/** Combines schedule lines, merging sessions that fall on the same day. */
const merge = (...groups: OpdDay[][]): OpdDay[] => {
  const byDay = new Map<Weekday, OpdDay>();
  for (const group of groups) {
    for (const o of group) {
      const have = byDay.get(o.day);
      if (have) {
        have.sessions.push(...o.sessions);
        if (o.note) have.note = have.note ? `${have.note}; ${o.note}` : o.note;
      } else {
        byDay.set(o.day, { day: o.day, sessions: [...o.sessions], ...(o.note ? { note: o.note } : {}) });
      }
    }
  }
  return WEEKDAYS.filter((d) => byDay.has(d)).map((d) => byDay.get(d) as OpdDay);
};
const MON_FRI: Weekday[] = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"];
const MON_SAT: Weekday[] = [...MON_FRI, "Saturday"];
const on = (days: Weekday[], start: string, end: string): OpdDay[] => days.map((d) => day(d, start, end));

